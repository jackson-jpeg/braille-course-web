export interface ResolvedStep {
  when?: string;
  href: string;
  label: string;
}

/** A step as a link, with the lesson title taken from the curriculum so it cannot drift. */
export function resolveStep(step: PathStep): ResolvedStep {
  if (step.kind === 'lesson') {
    const lesson = ALL_LESSONS.find((l) => l.slug === step.slug);
    if (!lesson) throw new Error(`world braille day: no lesson "${step.slug}"`);
    return { when: step.when, href: `/learn/${lesson.slug}`, label: `Lesson: ${lesson.title}` };
  }
  if (step.kind === 'game')
    return { when: step.when, href: `/games#${step.id}`, label: `Game: ${PATH_GAMES[step.id]}` };
  return { when: step.when, href: '#write-your-name', label: 'Write your names in braille (on this page)' };
}

/**
 * The home page links to this page during December and January only (World Braille Day is January 4,
 * and January is Braille Literacy Month). Dates are the server's, read in UTC.
 */
export function isWorldBrailleDaySeason(now: Date): boolean {
  const month = now.getUTCMonth();
  return month === 11 || month === 0;
}

