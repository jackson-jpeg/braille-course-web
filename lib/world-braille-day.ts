/**
 * World Braille Day page (/world-braille-day): the "write your name in braille" box and the
 * classroom paths.
 *
 * The name box writes uncontracted UEB through lib/braille/transcribe.ts and nothing else. It
 * accepts only what a name needs and the transcriber is checked for: the letters a to z in either
 * case, spaces, hyphens and apostrophes. Anything else (accented letters, digits, other
 * punctuation) is refused and pointed out, never dropped or guessed, because a name with a letter
 * silently missing is a different name. Nothing typed leaves the browser.
 */
import { type InventoryItem } from '@/lib/braille/inventory';
import { describeCells } from '@/lib/braille/prose';
import { type BrailleToken, TranscriptionError, transcribeTokens } from '@/lib/braille/transcribe';
import { ALL_LESSONS } from '@/lib/course-curriculum';

export const NAME_MAX_LENGTH = 30;

/** One print character the name box can write. */
const WRITABLE_RE = /^[A-Za-z '’-]$/;

export function isWritable(ch: string): boolean {
  return WRITABLE_RE.test(ch);
}

/** Spaces of any kind become one plain space; leading and trailing space is dropped. */
export function normalizeName(raw: string): string {
  return raw.normalize('NFC').replace(/\s+/gu, ' ').trim();
}

export type NameResult =
  | { status: 'empty' }
  | { status: 'too-long'; print: string }
  | {
      status: 'refused';
      print: string;
      /** Each character of the print, marked writable or not, for showing the problem in place. */
      marks: { ch: string; writable: boolean }[];
      /** The distinct characters that cannot be written, in the order typed. */
      unsupported: string[];
    }
  | { status: 'ok'; print: string; tokens: BrailleToken[] };

export function nameToBraille(raw: string): NameResult {
  const print = normalizeName(raw);
  if (print === '') return { status: 'empty' };
  const chars = [...print];
  if (chars.length > NAME_MAX_LENGTH) return { status: 'too-long', print };
  const marks = chars.map((ch) => ({ ch, writable: isWritable(ch) }));
  const unsupported = [...new Set(marks.filter((m) => !m.writable).map((m) => m.ch))];
  if (unsupported.length > 0) return { status: 'refused', print, marks, unsupported };
  try {
    return { status: 'ok', print, tokens: transcribeTokens(print) };
  } catch (e) {
    // Every writable character is checked, so this should not happen; if it ever does, refuse.
    if (e instanceof TranscriptionError) return { status: 'refused', print, marks, unsupported: [] };
    throw e;
  }
}

export interface DotRow {
  /** What the sign is: "capital letter indicator", "letter j", "hyphen". */
  name: string;
  /** Its dots, in words generated by lib/braille/prose.ts (describeCells). */
  dots: string;
}

/** One row per sign of the name, in reading order (spaces left out). */
export function dotRows(tokens: readonly BrailleToken[]): DotRow[] {
  return tokens.filter((t) => t.kind !== 'space').map((t) => ({ name: t.name, dots: describeCells(t.cells) }));
}

/** The name shown before anyone types, and the example in the copy. */
export const EXAMPLE_NAME = 'Louis';

/**
 * Names that exercise every rule the box can meet (capitals, capitalized words and passages,
 * hyphens, apostrophes), so the liblouis oracle checks the box's output on real shapes. Any other
 * name is made only of these signs, each checked one by one in the base inventory.
 */
export const SAMPLE_NAMES: readonly string[] = [
  EXAMPLE_NAME,
  'Louis Braille',
  'Ana',
  'Mary-Jane',
  'O’Brien',
  "D'Angelo",
  'DeShawn',
  'MacKenzie',
  'JO',
  'Jo Ann',
  'JO ANN',
  'ANN MARIE LEE',
  'McKAYLA',
  'Smith-Jones',
  'zoe',
];

export function brailleInventory(): InventoryItem[] {
  return SAMPLE_NAMES.map((n) => {
    const r = nameToBraille(n);
    if (r.status !== 'ok') throw new Error(`world braille day: sample name "${n}" is not writable`);
    return {
      where: 'page:world-braille-day',
      print: r.print,
      table: 'g1' as const,
      cells: r.tokens.flatMap((t) => t.cells),
    };
  });
}

