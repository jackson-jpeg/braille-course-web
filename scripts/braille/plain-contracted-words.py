#!/usr/bin/env python3
"""
Write lib/braille/data/plain-contracted-words.json: everyday words whose contracted (grade 2) UEB
is cell-for-cell the same as their uncontracted form, according to liblouis (en-ueb-g1 vs
en-ueb-g2). The AI worksheet builder may draw these words in contracted worksheets; every one is
re-checked by the liblouis oracle test (lib/worksheet-braille.ts brailleInventory).

Reads candidate words (lowercase a–z) as JSON on stdin:
  npx tsx scripts/braille/dump-candidate-words.ts | python3 scripts/braille/plain-contracted-words.py
"""
import json, os, sys
import louis

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "lib", "braille", "data", "plain-contracted-words.json")
words = sorted(set(json.load(sys.stdin)))
g1 = ["unicode.dis", "en-ueb-g1.ctb"]
g2 = ["unicode.dis", "en-ueb-g2.ctb"]
plain = [w for w in words if louis.translateString(g1, w) == louis.translateString(g2, w)]
with open(OUT, "w") as f:
    json.dump({"liblouis": louis.version(), "about": "Words whose contracted UEB equals their uncontracted UEB (liblouis). Generated by scripts/braille/plain-contracted-words.py.", "words": plain}, f, indent=1)
    f.write("\n")
print(f"{len(plain)} of {len(words)} candidate words are written the same in contracted braille", file=sys.stderr)
